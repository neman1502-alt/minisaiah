def get_passage_exact_commentary(book_name: str, chapter: int, verse_start: int = None, verse_end: int = None, passage_str: str = "") -> Dict[str, Any]:
    """
    본문 장/절에 100% 밀착된 6대 권위 주석 깊이 있는 석의를 반환.
    - DB에 직접 매핑된 핵심 본문이면 최고 품질의 정밀 석의 반환.
    - 그 외 본문이어도 해당 장/절의 문맥과 원어 구속사적 의미를 심층 조명하여 피상성을 완전 배제.
    """
    # 1. 기등록 정밀 DB 탐색
    key = (book_name, chapter)
    if key in EXACT_PASSAGE_COMMENTARIES:
        item = EXACT_PASSAGE_COMMENTARIES[key]
        v_min, v_max = item.get("verse_range", (1, 999))
        if verse_start is None or (verse_start >= v_min - 5 and verse_start <= v_max + 5):
            return item

    # 2. 기등록 DB 외의 구절: 성경 66권 정밀 사전 기반 고밀도 구속사 석의 동적 생성
