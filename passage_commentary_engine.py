# 3. D드라이브 OCR 텍스트 정제기 및 심층 융합기
# ─────────────────────────────────────────────────────────────
import re

def clean_ocr_excerpt(raw_text: str, max_chars: int = 250) -> str:
    """
    D드라이브 실물 파일에서 추출된 OCR 원문에서
    글자 깨짐(외계어, 자모 분리, 목차 번호 나열 등)을 엄격히 판별하고 정제.
    불량 텍스트일 경우 빈 문자열 반환하여 보고서 오염을 원천 차단.
    """
    if not raw_text or len(raw_text.strip()) < 20:
        return ""

    text = raw_text.strip()

    # 1. 스캔본 목차/서문 노이즈 패턴 감지
    noise_patterns = [
        r"편집자\s*서문", r"저자\s*서문", r"약어표", r"차\s*례",
        r"\.{4,}", r"…{2,}", r"[-_]{4,}",
        r"제\s*\d+\s*부", r"총서론", r"정경\s*문제",
        r"[l\|]{2,}", r"[\da-zA-Z]{1,3}뼈", r"ka뼈", r"kg뼈",
        r"톨훌", r"쟁갱", r"쩔대쩍", r"하나념", r"샤랍은",
    ]
    for np in noise_patterns:
        if re.search(np, text):
            return ""

    # 2. 한글 완성형 대비 비정상 자모/특수기호 비율 검사
    total_chars = len(text)
    hangul_complete = len(re.findall(r"[가-힣]", text))
    jamo_broken = len(re.findall(r"[ㄱ-ㅎㅏ-ㅣ]", text))
    weird_symbols = len(re.findall(r"[~^`\|\\]", text))

    if total_chars > 0:
        if (hangul_complete / total_chars) < 0.45:  # 완성형 한글 비율이 45% 미만이면 탈락
            return ""
        if jamo_broken > 3 or weird_symbols > 5:  # 깨진 자모나 이상 기호가 많으면 탈락
            return ""

    # 3. 텍스트 공백 정돈
    clean = re.sub(r"\s+", " ", text).strip()
    if len(clean) > max_chars:
        clean = clean[:max_chars].rstrip() + "..."
    return clean


def get_integrated_passage_commentary(
    book_name: str,
    chapter: int,
    verse_start: int = None,
    verse_end: int = None,
    passage_str: str = "",
    d_insights: dict = None
) -> Dict[str, Any]:
    """
    본문 밀착형 6대 주석 심층 석의와 D드라이브 실물 자료를 융합한 최종 주석 패키지 생성.
    - 본문 장/절에 100% 밀착된 심층 석의 보장 (피상적 개론 완전 배제)
    - 글자 깨짐 없는 품격 높은 한국어 학술 문체
    - 깨끗한 D드라이브 실물 인용문이 있을 경우에만 품격 있게 원본 인용 병기
    """
    base = get_passage_exact_commentary(book_name, chapter, verse_start, verse_end, passage_str)
    result = dict(base)

    if not d_insights or not d_insights.get("success"):
        return result

    # D드라이브 실물 인용문 정제 결합
    excerpts = {
        "oxford": clean_ocr_excerpt(d_insights.get("oxford", {}).get("excerpt", "")),
        "grace": clean_ocr_excerpt(d_insights.get("grace", {}).get("excerpt", "")),
        "calvin": clean_ocr_excerpt(d_insights.get("calvin", {}).get("excerpt", "")),
        "park": clean_ocr_excerpt(d_insights.get("park", {}).get("excerpt", "")),
        "wbc": clean_ocr_excerpt(d_insights.get("wbc", {}).get("excerpt", "")),
        "pastoral": clean_ocr_excerpt(d_insights.get("pastoral", {}).get("excerpt", ""))
    }

    # 옥스포드/호크마에 정제된 인용문 병기
    if excerpts["oxford"]:
        result["oxford_hockma"] += f" (D드라이브 원본 인용: \"{excerpts['oxford']}\")"
    elif excerpts["grace"]:
        result["oxford_hockma"] += f" (D드라이브 종합강해 인용: \"{excerpts['grace']}\")"

    # 칼빈/박윤선에 정제된 인용문 병기
    if excerpts["calvin"]:
        result["calvin_park"] += f" (칼빈 주석 원본 인용: \"{excerpts['calvin']}\")"
    elif excerpts["park"]:
        result["calvin_park"] += f" (박윤선 주석 원본 인용: \"{excerpts['park']}\")"

    # WBC에 정제된 인용문 병기
    if excerpts["wbc"]:
        result["wbc_ivp"] += f" (WBC 원본 인용: \"{excerpts['wbc']}\")"

    # 목성연에 정제된 인용문 병기
    if excerpts["pastoral"]:
        result["moksungyeon"] += f" (목성연 교재 원본 인용: \"{excerpts['pastoral']}\")"

    return result

